import { test, expect } from '@playwright/test'
const ids=['istanbul-maiden-tower','istanbul-maiden-night','istanbul-galata','istanbul-bosphorus','istanbul-ortakoy','istanbul-rooftops','cappadocia','aegean-coast','paris-eiffel','tokyo-rain']
test('all scenes: decode, sound, favorites, settings, fullscreen, coffee, exit, resize',async({page})=>{
 test.setTimeout(180000)
 const errors:string[]=[];const bad:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('console',m=>{if(m.type()==='error'||m.type()==='warning')errors.push(m.text())})
 page.on('response',r=>{if(r.status()>=400)bad.push(r.url())})
 for(const id of ids){
  await page.goto('/#/scene/'+id)
  await expect(page.locator('.viewer')).toHaveClass(/is-ready/)
  await expect(page.locator('.art-failed')).toHaveCount(0)
  await expect(page.locator('[data-testid="couple-layer"]')).toBeVisible()
  await expect(page.locator('.couple-base')).toHaveCount(1)
  expect(await page.locator('img').evaluateAll(imgs=>imgs.every(img=>(img as HTMLImageElement).complete&&(img as HTMLImageElement).naturalWidth>0))).toBe(true)
  await page.mouse.move(50,50)
  if(await page.getByRole('button',{name:'Ortam sesini aç',exact:true}).count())await page.getByRole('button',{name:'Ortam sesini aç',exact:true}).click()
  await expect(page.getByRole('button',{name:'Ortam sesini kapat',exact:true})).toBeVisible()
  await page.waitForTimeout(500)
  expect(await page.locator('.sound-caption').textContent()).not.toContain('yüklenemedi')
  const favorite=page.getByRole('button',{name:/Favoriye ekle|Favorilerden çıkar/})
  await favorite.click()
  await page.getByRole('button',{name:'Ayarlar',exact:true}).click()
  await page.getByLabel('Kalite',{exact:true}).selectOption('low')
  await expect(page.locator('.scene-art')).toHaveClass(/quality-low/)
  await page.getByLabel('Kalite',{exact:true}).selectOption('balanced')
  await page.getByRole('button',{name:'Ayarları kapat'}).click()
  await page.getByRole('button',{name:'Tam ekran',exact:true}).click()
  if(await page.evaluate(()=>Boolean(document.fullscreenElement)))await page.evaluate(()=>document.exitFullscreen())
  await page.getByRole('button',{name:'Kahve modu',exact:true}).click()
  await expect(page.locator('.viewer')).toHaveClass(/coffee-mode/)
  await page.mouse.click(200,150)
  await expect(page.locator('.viewer')).toHaveClass(/coffee-mode/)
  await page.getByRole('button',{name:'Kahve modundan çık'}).click()
  for(const [width,height] of [[1920,1080],[375,667],[390,844],[430,932],[667,375],[844,390],[932,430]]){
   await page.setViewportSize({width,height})
   expect(await page.evaluate(()=>({x:document.documentElement.scrollWidth-innerWidth,y:document.documentElement.scrollHeight-innerHeight}))).toEqual({x:0,y:0})
  }
  await page.mouse.move(100,110)
  await page.getByRole('button',{name:'Manzara değiştir'}).click()
  await expect(page.locator('.picker')).toBeVisible()
 }
 expect(errors).toEqual([]);expect(bad).toEqual([])
})
