test('visual viewport drives portrait, landscape and fullscreen layout transitions',async({page})=>{
 test.setTimeout(90000)
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error'||message.type()==='warning')errors.push(message.text())})
 const viewer=page.locator('.viewer')
 const expectViewport=async(width:number,height:number,landscape:boolean)=>{
  await expect(viewer).toHaveAttribute('data-viewport-width',String(width))
  await expect(viewer).toHaveAttribute('data-viewport-height',String(height))
  await expect(viewer).toHaveClass(landscape?/is-landscape/:/is-portrait/)
  if(landscape&&height<=600)await expect(viewer).toHaveClass(/is-compact-landscape/)
  const box=await viewer.boundingBox()
  expect(Math.round(box?.width??0)).toBe(width)
  expect(Math.round(box?.height??0)).toBe(height)
 }

 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await expect(viewer).toHaveClass(/is-ready/)
 await expectViewport(390,844,false)
 await page.setViewportSize({width:844,height:390})
 await expectViewport(844,390,true)

 await page.setViewportSize({width:430,height:932})
 await expectViewport(430,932,false)
 await page.setViewportSize({width:932,height:430})
 await expectViewport(932,430,true)
 await page.setViewportSize({width:375,height:667})
 await expectViewport(375,667,false)
 await page.setViewportSize({width:667,height:375})
 await expectViewport(667,375,true)

 await page.setViewportSize({width:390,height:844})
 await page.reload()
 await expect(viewer).toHaveClass(/is-ready/)
 await page.getByRole('button',{name:'Tam ekran',exact:true}).click()
 await expect(viewer).toHaveAttribute('data-fullscreen','true')
 await page.setViewportSize({width:844,height:390})
 await expectViewport(844,390,true)
 if(await page.evaluate(()=>Boolean(document.fullscreenElement)))await page.evaluate(()=>document.exitFullscreen())
 else await page.getByRole('button',{name:'Tam ekran',exact:true}).click()
 await expect(viewer).toHaveAttribute('data-fullscreen','false')
 await page.setViewportSize({width:390,height:844})
 await expectViewport(390,844,false)
 await page.setViewportSize({width:844,height:390})
 await expectViewport(844,390,true)
 expect(errors).toEqual([])
})
test('immersive fallback stays responsive when native fullscreen is unavailable',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error'||message.type()==='warning')errors.push(message.text())})
 await page.addInitScript(()=>Object.defineProperty(HTMLElement.prototype,'requestFullscreen',{value:undefined,configurable:true}))
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 const viewer=page.locator('.viewer')
 await expect(viewer).toHaveClass(/is-ready/)
 await page.getByRole('button',{name:'Tam ekran',exact:true}).click()
 await expect(viewer).toHaveClass(/is-immersive/)
 await expect(viewer).toHaveAttribute('data-fullscreen','true')
 await page.setViewportSize({width:844,height:390})
 await expect(viewer).toHaveClass(/is-landscape/)
 await expect(viewer).toHaveAttribute('data-viewport-width','844')
 await expect(viewer).toHaveAttribute('data-viewport-height','390')
 await page.getByRole('button',{name:'Tam ekran',exact:true}).click()
 await expect(viewer).not.toHaveClass(/is-immersive/)
 await expect(viewer).toHaveAttribute('data-fullscreen','false')
 expect(errors).toEqual([])
})
